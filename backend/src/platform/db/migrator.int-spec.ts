import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { emptyDatabase } from '../../../test/kit/postgres';
import { connectDatabase, type Database } from './database';
import { migrationFiles, readModuleLists } from './migration-files';
import { Migrator } from './migrator';

function fixtureDir(files: Record<string, string>): string {
  const dir = mkdtempSync(join(tmpdir(), 'pao-migrations-'));
  for (const [path, sql] of Object.entries(files)) {
    mkdirSync(join(dir, path.split('/')[0] ?? ''), { recursive: true });
    writeFileSync(join(dir, path), sql);
  }
  return dir;
}

async function schemaCount(db: Database, modules: readonly string[]): Promise<number> {
  const { rows } = await db.query<{ n: string }>(
    'SELECT count(*) AS n FROM information_schema.schemata WHERE schema_name = ANY($1)',
    [modules],
  );
  return Number(rows[0]?.n);
}

async function fresh(): Promise<Database> {
  return connectDatabase(await emptyDatabase());
}

describe('Migrator over the real migrations', () => {
  const { modules } = readModuleLists();

  it('round-trips up, down and up', async () => {
    const db = await fresh();
    const m = new Migrator(db, migrationFiles(), modules);
    await m.up();
    expect(await schemaCount(db, modules)).toBe(modules.length);
    await m.up();
    const { rows } = await db.query<{ version_id: string }>(
      'SELECT version_id FROM goose_identity ORDER BY id',
    );
    expect(rows.map((r) => r.version_id)).toEqual(['0', '1', '2']);
    await m.down();
    expect(await schemaCount(db, modules)).toBe(0);
    await m.up();
    expect(await schemaCount(db, modules)).toBe(modules.length);
    await db.close();
  });

  it('treats versions recorded by goose as applied', async () => {
    const db = await fresh();
    await db.query(`CREATE TABLE goose_audit (
      id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      version_id bigint NOT NULL, is_applied boolean NOT NULL,
      tstamp timestamp NOT NULL DEFAULT now())`);
    await db.query('INSERT INTO goose_audit (version_id, is_applied) VALUES (0, true), (1, true)');
    await new Migrator(db, migrationFiles(), ['audit']).up();
    expect(await schemaCount(db, ['audit'])).toBe(0);
    await db.close();
  });

  it('fails for unknown or invalid module names', async () => {
    const db = await fresh();
    await expect(new Migrator(db, migrationFiles(), ['nope']).up()).rejects.toThrow(
      'no migrations found for module nope',
    );
    await expect(new Migrator(db, migrationFiles(), ['nope']).down()).rejects.toThrow();
    await expect(new Migrator(db, migrationFiles(), ['../escape']).up()).rejects.toThrow(
      'invalid migration module name',
    );
    await db.close();
  });
});

describe('Migrator over fixtures', () => {
  it('reports failing statements in either direction', async () => {
    const dir = fixtureDir({
      'bad_up/0001_x.sql':
        '-- +goose Up\nSELECT missing_column FROM nowhere;\n-- +goose Down\nSELECT 1;\n',
      'bad_down/0001_x.sql':
        '-- +goose Up\nSELECT 1;\n-- +goose Down\nSELECT missing_column FROM nowhere;\n',
    });
    const db = await fresh();
    await expect(new Migrator(db, migrationFiles(dir), ['bad_up']).up()).rejects.toThrow(
      'migration bad_up/0001_x.sql failed',
    );
    const m = new Migrator(db, migrationFiles(dir), ['bad_down']);
    await m.up();
    await expect(m.down()).rejects.toThrow('migration bad_down/0001_x.sql failed');
    await db.close();
  });

  it('refuses out-of-order files and applied versions without a file', async () => {
    const dir = fixtureDir({
      'gap/0001_a.sql': '-- +goose Up\nSELECT 1;\n',
      'gap/0003_c.sql': '-- +goose Up\nSELECT 1;\n',
    });
    const db = await fresh();
    await new Migrator(db, migrationFiles(dir), ['gap']).up();
    writeFileSync(join(dir, 'gap/0002_b.sql'), '-- +goose Up\nSELECT 1;\n');
    await expect(new Migrator(db, migrationFiles(dir), ['gap']).up()).rejects.toThrow(
      'found 1 missing (out-of-order) migration(s): gap/0002_b.sql',
    );
    await db.query('INSERT INTO goose_gap (version_id, is_applied) VALUES (9, true)');
    await expect(new Migrator(db, migrationFiles(dir), ['gap']).down()).rejects.toThrow(
      'no file for applied version 9',
    );
    await db.close();
  });

  it('runs NO TRANSACTION migrations outside a transaction', async () => {
    const dir = fixtureDir({
      'conc/0001_a.sql':
        '-- +goose Up\nCREATE TABLE conc_t (v int);\n-- +goose Down\nDROP TABLE conc_t;\n',
      'conc/0002_b.sql':
        '-- +goose NO TRANSACTION\n-- +goose Up\nCREATE INDEX CONCURRENTLY conc_i ON conc_t (v);\n-- +goose Down\nDROP INDEX CONCURRENTLY conc_i;\n',
    });
    const db = await fresh();
    const m = new Migrator(db, migrationFiles(dir), ['conc']);
    await m.up();
    await m.down();
    const { rows } = await db.query("SELECT 1 FROM pg_tables WHERE tablename = 'conc_t'");
    expect(rows).toHaveLength(0);
    await db.close();
  });
});

describe('Migrator losing its connection', () => {
  it('fails and discards the connection', async () => {
    const dir = fixtureDir({
      'lost/0001_a.sql': '-- +goose Up\nSELECT pg_terminate_backend(pg_backend_pid());\n',
    });
    const db = await fresh();
    await expect(new Migrator(db, migrationFiles(dir), ['lost']).up()).rejects.toThrow();
    await expect(db.ping()).resolves.toBeUndefined();
    await db.close();
  });
});

describe('readModuleLists', () => {
  it('reads the module order and rejects malformed lists', () => {
    const lists = readModuleLists();
    expect(lists.modules[0]).toBe('identity');
    expect(lists.outboxModules).not.toContain('audit');
    const bad = fixtureDir({ 'x/0001_a.sql': '' });
    writeFileSync(join(bad, 'modules.json'), '{"modules":["../x"],"outboxModules":[]}');
    expect(() => readModuleLists(bad)).toThrow('modules must be a list of module names');
    writeFileSync(join(bad, 'modules.json'), '{"modules":[],"outboxModules":"x"}');
    expect(() => readModuleLists(bad)).toThrow('outboxModules must be');
  });
});
