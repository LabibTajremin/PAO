import { escapeIdentifier, type PoolClient } from 'pg';
import { type Database } from './database';
import { type GooseMigration } from './goose-parser';

/** Loads one module's migrations, sorted by version. */
export type MigrationLoader = (module: string) => Promise<GooseMigration[]>;

// Serialises concurrent migrators (two deploys starting at once) on one database.
const MIGRATION_LOCK_KEY = 7_041_998_310;

// The exact table goose v3 creates, so a database migrated by the Go backend is up to
// date here and the other way round.
const createVersionTable = (table: string): string => `CREATE TABLE ${table} (
  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  version_id bigint NOT NULL,
  is_applied boolean NOT NULL,
  tstamp timestamp NOT NULL DEFAULT now()
)`;

/**
 * Applies the per-module goose migrations. Each module keeps its own version table
 * (`goose_<module>`), so a module's schema can later move to its own database unchanged.
 */
export class Migrator {
  constructor(
    private readonly db: Database,
    private readonly load: MigrationLoader,
    private readonly modules: readonly string[],
  ) {}

  /** Applies every pending migration of every module, in module order. */
  up(): Promise<void> {
    return this.locked(async (client) => {
      for (const module of this.modules) {
        await this.moduleUp(client, module);
      }
    });
  }

  /** Rolls every module back to version zero, in reverse module order. */
  down(): Promise<void> {
    return this.locked(async (client) => {
      for (const module of [...this.modules].reverse()) {
        await this.moduleDown(client, module);
      }
    });
  }

  private async locked(fn: (client: PoolClient) => Promise<void>): Promise<void> {
    const client = await this.db.checkout();
    let lost = false;
    try {
      await client.query('SELECT pg_advisory_lock($1)', [MIGRATION_LOCK_KEY]);
      await fn(client);
    } finally {
      // A lost connection already dropped the lock; its client must not be reused.
      await client
        .query('SELECT pg_advisory_unlock($1)', [MIGRATION_LOCK_KEY])
        .catch(() => (lost = true));
      client.done(lost);
    }
  }

  private async moduleUp(client: PoolClient, module: string): Promise<void> {
    const migrations = await this.load(module);
    const table = await ensureVersionTable(client, module);
    const applied = await appliedVersions(client, table);
    const latest = Math.max(...applied);
    const pending = migrations.filter((m) => !applied.has(m.version));
    const missing = pending.filter((m) => m.version < latest);
    if (missing.length > 0) {
      throw new Error(
        `migrate ${module} up: found ${missing.length} missing (out-of-order) migration(s): ` +
          missing.map((m) => m.source).join(', '),
      );
    }
    for (const m of pending) {
      await apply(client, m, m.up, () =>
        client.query(`INSERT INTO ${table} (version_id, is_applied) VALUES ($1, $2)`, [
          m.version,
          true,
        ]),
      );
    }
  }

  private async moduleDown(client: PoolClient, module: string): Promise<void> {
    const migrations = new Map((await this.load(module)).map((m) => [m.version, m]));
    const table = await ensureVersionTable(client, module);
    const applied = [...(await appliedVersions(client, table))].filter((v) => v > 0);
    for (const version of applied.sort((a, b) => b - a)) {
      const m = migrations.get(version);
      if (!m) {
        throw new Error(`migrate ${module} down: no file for applied version ${version}`);
      }
      await apply(client, m, m.down, () =>
        client.query(`DELETE FROM ${table} WHERE version_id = $1`, [version]),
      );
    }
  }
}

async function ensureVersionTable(client: PoolClient, module: string): Promise<string> {
  const name = 'goose_' + module;
  const table = escapeIdentifier(name);
  const { rows } = await client.query<{ exists: boolean }>(
    'SELECT EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = current_schema() AND tablename = $1)',
    [name],
  );
  if (rows[0]?.exists !== true) {
    await inTransaction(client, async () => {
      await client.query(createVersionTable(table));
      await client.query(`INSERT INTO ${table} (version_id, is_applied) VALUES (0, true)`);
    });
  }
  return table;
}

async function appliedVersions(client: PoolClient, table: string): Promise<Set<number>> {
  const { rows } = await client.query<{ version_id: string }>(`SELECT version_id FROM ${table}`);
  return new Set(rows.map((r) => Number(r.version_id)));
}

async function apply(
  client: PoolClient,
  m: GooseMigration,
  statements: readonly string[],
  record: () => Promise<unknown>,
): Promise<void> {
  const run = async (): Promise<void> => {
    for (const statement of statements) {
      await client.query(statement);
    }
    await record();
  };
  try {
    await (m.noTransaction ? run() : inTransaction(client, run));
  } catch (cause) {
    throw new Error(`migration ${m.source} failed`, { cause });
  }
}

async function inTransaction(client: PoolClient, fn: () => Promise<void>): Promise<void> {
  await client.query('BEGIN');
  try {
    await fn();
    await client.query('COMMIT');
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  }
}
