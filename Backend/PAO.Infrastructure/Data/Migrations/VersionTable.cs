using Npgsql;

namespace PAO.Infrastructure.Data.Migrations;

/// <summary>The `goose_&lt;module&gt;` version tables.</summary>
internal static class VersionTable
{
    // The exact table goose v3 creates (and the NestJS migrator copied).
    private const string Create = """
        CREATE TABLE {0} (
          id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
          version_id bigint NOT NULL,
          is_applied boolean NOT NULL,
          tstamp timestamp NOT NULL DEFAULT now()
        )
        """;

    /// <summary>Creates the module's table with the version-zero row when missing; returns its quoted name.</summary>
    public static async Task<string> Ensure(NpgsqlConnection connection, string module, CancellationToken cancellationToken)
    {
        var name = "goose_" + module;
        var table = PostgresErrors.Quote(name);
        await using var exists = new NpgsqlCommand(
            "SELECT EXISTS (SELECT 1 FROM pg_tables WHERE schemaname = current_schema() AND tablename = $1)", connection);
        exists.Parameters.Add(new NpgsqlParameter { Value = name });
        if (await exists.ExecuteScalarAsync(cancellationToken) is not true)
        {
            await Sql.InTransaction(connection, async () =>
            {
                await Sql.Execute(connection, string.Format(System.Globalization.CultureInfo.InvariantCulture, Create, table), cancellationToken);
                await Sql.Execute(connection, $"INSERT INTO {table} (version_id, is_applied) VALUES (0, true)", cancellationToken);
            }, cancellationToken);
        }
        return table;
    }

    /// <summary>The versions recorded in `table`.</summary>
    public static async Task<HashSet<long>> Applied(NpgsqlConnection connection, string table, CancellationToken cancellationToken)
    {
        var versions = new HashSet<long>();
        await using var command = new NpgsqlCommand($"SELECT version_id FROM {table}", connection);
        await using var reader = await command.ExecuteReaderAsync(cancellationToken);
        while (await reader.ReadAsync(cancellationToken))
        {
            versions.Add(reader.GetInt64(0));
        }
        return versions;
    }
}

/// <summary>Small helpers for raw SQL on one connection (migrator, scheduler, outbox).</summary>
internal static class Sql
{
    /// <summary>Runs one statement with positional parameters.</summary>
    public static async Task<int> Execute(NpgsqlConnection connection, string sql, CancellationToken cancellationToken, params object[] values)
    {
        await using var command = new NpgsqlCommand(sql, connection);
        foreach (var value in values)
        {
            command.Parameters.Add(new NpgsqlParameter { Value = value });
        }
        return await command.ExecuteNonQueryAsync(cancellationToken);
    }

    /// <summary>Runs `run` between BEGIN and COMMIT, rolling back when it throws.</summary>
    public static async Task InTransaction(NpgsqlConnection connection, Func<Task> run, CancellationToken cancellationToken)
    {
        await Execute(connection, "BEGIN", cancellationToken);
        try
        {
            await run();
            await Execute(connection, "COMMIT", cancellationToken);
        }
        catch
        {
            await Execute(connection, "ROLLBACK", CancellationToken.None);
            throw;
        }
    }
}
