using System.Globalization;
using System.Text;
using PAO.Infrastructure.Data.Migrations;

namespace PAO.Migrator;

/// <summary>
/// Writes "DB Changes" as one script (`bundle/schema.sql`) that applies exactly what
/// `migrate up` applies and records the same `goose_&lt;module&gt;` rows, for a SQL editor
/// such as Neon's. Each migration is one DO block that runs only when its version is not
/// recorded yet, so the script is idempotent and atomic per migration like the migrator.
/// </summary>
public static class SchemaBundle
{
    /// <summary>Dollar-quote tag around each DO block.</summary>
    public const string BlockTag = "$pao_bundle$";

    /// <summary>Dollar-quote tag around each statement inside a block.</summary>
    public const string StatementTag = "$pao_stmt$";

    // Same key as GooseMigrator, so the script and a deploy never migrate at once.
    private const long LockKey = 7_041_998_310;

    /// <summary>The script for `modules` (in order), each module's migrations from `load`.</summary>
    public static string Build(IReadOnlyList<string> modules, Func<string, IReadOnlyList<GooseMigration>> load)
    {
        var sql = new StringBuilder();
        sql.Append(Header);
        sql.Append(Line($"SELECT pg_advisory_lock({LockKey});"));
        foreach (var module in modules)
        {
            AppendModule(sql, module, load(module));
        }
        sql.Append(Line($"\nSELECT pg_advisory_unlock({LockKey});"));
        return sql.ToString();
    }

    private static void AppendModule(StringBuilder sql, string module, IReadOnlyList<GooseMigration> migrations)
    {
        var table = "goose_" + module;
        sql.Append(Line($"\n-- ===== {module} ====="));
        // The exact table and version-zero row GooseMigrator (VersionTable) creates.
        sql.Append(Line($"""
            CREATE TABLE IF NOT EXISTS {table} (
              id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
              version_id bigint NOT NULL,
              is_applied boolean NOT NULL,
              tstamp timestamp NOT NULL DEFAULT now()
            );
            INSERT INTO {table} (version_id, is_applied) SELECT 0, true WHERE NOT EXISTS (SELECT 1 FROM {table});
            """));
        foreach (var m in migrations)
        {
            AppendMigration(sql, table, m);
        }
    }

    private static void AppendMigration(StringBuilder sql, string table, GooseMigration m)
    {
        if (m.NoTransaction)
        {
            throw new InvalidOperationException(
                $"bundle: {m.Source} uses NO TRANSACTION, which a DO block cannot run; apply it with `migrate up`");
        }
        var version = m.Version.ToString(CultureInfo.InvariantCulture);
        sql.Append(Line($"\n-- {m.Source}"));
        sql.Append(Line($"DO {BlockTag}"));
        sql.Append(Line("BEGIN"));
        sql.Append(Line($"  IF NOT EXISTS (SELECT 1 FROM {table} WHERE version_id = {version}) THEN"));
        sql.Append(Line($"    IF EXISTS (SELECT 1 FROM {table} WHERE version_id > {version}) THEN"));
        sql.Append(Line($"      RAISE EXCEPTION 'migrate up: {m.Source} is missing (out of order)';"));
        sql.Append(Line("    END IF;"));
        foreach (var statement in m.Up)
        {
            if (statement.Contains(StatementTag, StringComparison.Ordinal) || statement.Contains(BlockTag, StringComparison.Ordinal))
            {
                throw new InvalidOperationException($"bundle: {m.Source} contains a reserved dollar-quote tag");
            }
            sql.Append(Line($"    EXECUTE {StatementTag}{statement}{StatementTag};"));
        }
        sql.Append(Line($"    INSERT INTO {table} (version_id, is_applied) VALUES ({version}, true);"));
        sql.Append(Line("  END IF;"));
        sql.Append(Line("END"));
        sql.Append(Line($"{BlockTag};"));
    }

    private static string Line(string text) => text + "\n";

    private const string Header = """
        -- Generated by `migrate bundle` (Backend/scripts/gen-db-bundle.sh) from "DB Changes";
        -- do not edit. CI fails when it is out of date.
        --
        -- Applies every migration in modules.json order, exactly what `/app/migrate up`
        -- applies, and records the same versions in the goose_<module> tables, so running
        -- this file in a SQL editor (Neon's, psql -f) equals `migrate up`. Idempotent: a
        -- migration already recorded is skipped, so it is safe on an empty database, on a
        -- partly migrated one and when run twice. Each migration commits on its own, as with
        -- the migrator. Load the reference data afterwards with seed.sql.

        """;
}
