using System.Collections;
using Npgsql;
using PAO.EF;
using PAO.EF.Connection;
using PAO.Infrastructure.Data.Migrations;
using PAO.Migrator;
using PAO.TestKit;

namespace PAO.IntegrationTests;

public sealed class GooseMigratorTests : IAsyncLifetime
{
    private string url = string.Empty;
    private NpgsqlDataSource dataSource = null!;
    private readonly MigrationFiles files = new(TestDatabases.MigrationsDirectory);

    public async ValueTask InitializeAsync()
    {
        url = await TestDatabases.CreateEmpty();
        dataSource = PaoDbContextSetup.CreateDataSource(PostgresUrl.ToConnectionString(url));
    }

    public async ValueTask DisposeAsync()
    {
        await dataSource.DisposeAsync();
        await TestDatabases.Drop(url);
    }

    private GooseMigrator Migrator(Func<string, IReadOnlyList<GooseMigration>>? load = null, params string[] modules) =>
        new(dataSource, load ?? files.Load, modules.Length > 0 ? modules : files.ReadModuleLists().Modules);

    private async Task<List<long>> Versions(string module)
    {
        await using var command = dataSource.CreateCommand($"SELECT version_id FROM goose_{module} ORDER BY id");
        await using var reader = await command.ExecuteReaderAsync();
        var versions = new List<long>();
        while (await reader.ReadAsync())
        {
            versions.Add(reader.GetInt64(0));
        }
        return versions;
    }

    private async Task Sql(string sql)
    {
        await using var command = dataSource.CreateCommand(sql);
        await command.ExecuteNonQueryAsync();
    }

    [Fact]
    public async Task Applies_every_script_once_and_records_goose_versions()
    {
        await Migrator().Up(CancellationToken.None);
        await Migrator().Up(CancellationToken.None);
        Assert.Equal([0L, 1L, 2L, 3L], await Versions("identity"));
        Assert.Equal([0L, 1L, 2L], await Versions("booking"));
        await using var columns = dataSource.CreateCommand(
            "SELECT string_agg(column_name || ':' || data_type, ',' ORDER BY ordinal_position) FROM information_schema.columns WHERE table_name = 'goose_identity'");
        Assert.Equal("id:integer,version_id:bigint,is_applied:boolean,tstamp:timestamp without time zone", await columns.ExecuteScalarAsync());
        await Migrator().Down(CancellationToken.None);
        Assert.Equal([0L], await Versions("identity"));
    }

    [Fact]
    public async Task A_database_a_goose_migrator_left_at_version_one_carries_over()
    {
        // Exactly what a goose migrator does for version 1 of a module.
        var first = files.Load("identity")[0];
        await Sql("CREATE TABLE \"goose_identity\" (\n  id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,\n  version_id bigint NOT NULL,\n  is_applied boolean NOT NULL,\n  tstamp timestamp NOT NULL DEFAULT now()\n)");
        await Sql("INSERT INTO \"goose_identity\" (version_id, is_applied) VALUES (0, true), (1, true)");
        foreach (var statement in first.Up)
        {
            await Sql(statement);
        }
        await Migrator(null, "identity").Up(CancellationToken.None);
        Assert.Equal([0L, 1L, 2L, 3L], await Versions("identity"));
        await using var roles = dataSource.CreateCommand("SELECT count(*) FROM identity.roles");
        Assert.Equal(6L, await roles.ExecuteScalarAsync());
    }

    [Fact]
    public async Task Refuses_out_of_order_scripts_and_reports_failing_ones()
    {
        await Migrator(null, "identity").Up(CancellationToken.None);
        IReadOnlyList<GooseMigration> WithGap(string m) => [.. files.Load(m), new GooseMigration(1_5, "identity/0001_5_late.sql", ["SELECT 1"], [], false)];
        await Sql("DELETE FROM goose_identity WHERE version_id = 2; INSERT INTO goose_identity (version_id, is_applied) VALUES (20, true)");
        var gap = await Assert.ThrowsAsync<InvalidOperationException>(() => Migrator(WithGap, "identity").Up(CancellationToken.None));
        Assert.Contains("missing (out-of-order)", gap.Message, StringComparison.Ordinal);
        IReadOnlyList<GooseMigration> Broken(string m) => [new GooseMigration(30, "x/0030_bad.sql", ["SELECT nope FROM nowhere"], [], true)];
        var failed = await Assert.ThrowsAsync<InvalidOperationException>(() => Migrator(Broken, "audit").Up(CancellationToken.None));
        Assert.Equal("migration x/0030_bad.sql failed", failed.Message);
        await Assert.ThrowsAsync<InvalidOperationException>(() => Migrator(Broken, "identity").Down(CancellationToken.None));
    }

    [Fact]
    public async Task The_command_line_tool_applies_the_scripts()
    {
        var output = new StringWriter();
        Assert.Equal(2, await new[] { "down" }.RunMigrator(new Hashtable(), TestDatabases.MigrationsDirectory, output));
        Assert.Equal(1, await new[] { "up" }.RunMigrator(new Hashtable(), TestDatabases.MigrationsDirectory, output));
        Assert.Equal(0, await new[] { "up" }.RunMigrator(new Hashtable { ["Database__Url"] = url }, TestDatabases.MigrationsDirectory, output));
        Assert.Equal(0, await new[] { "up" }.RunMigrator(new Hashtable { ["DATABASE_URL"] = url }, TestDatabases.MigrationsDirectory, output));
        Assert.Contains(MigratorCommand.Usage, output.ToString(), StringComparison.Ordinal);
        Assert.Contains("migrate up: done", output.ToString(), StringComparison.Ordinal);
    }
}
